import { useState, type FormEvent } from "react";
import { KeyRound, Loader2, ShieldCheck, Wifi } from "lucide-react";
import { getApiToken, getRuntimeConfig, isTauri, setApiBaseUrl } from "../lib/api";
import { useApp } from "../store/app";
import { Button } from "./ui/button";
import { Input } from "./ui/input";

export default function TokenGate() {
  const setToken = useApp((state) => state.setToken);
  const error = useApp((state) => state.error);
  const [tokenValue, setTokenValue] = useState(getApiToken());
  const [base, setBase] = useState(getRuntimeConfig().baseUrl);
  const [busy, setBusy] = useState(false);

  const submit = async (event: FormEvent) => {
    event.preventDefault();
    setBusy(true);
    setApiBaseUrl(base);
    try {
      await setToken(tokenValue.trim());
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="flex min-h-screen items-center justify-center px-4 py-10">
      <div className="w-full max-w-md">
        <div className="mb-8 flex items-center gap-3">
          <div className="flex h-11 w-11 items-center justify-center rounded-xl border border-accent/30 bg-accent/10 text-accent shadow-glow">
            <svg viewBox="0 0 24 24" className="h-6 w-6" fill="none" aria-hidden="true">
              <path
                d="M6 19V5h3l7.5 9.5V5H20v14h-3.2L9.5 9.2V19H6Z"
                fill="currentColor"
              />
              <path d="M6 21h12" stroke="currentColor" strokeWidth="1.6" strokeLinecap="round" />
            </svg>
          </div>
          <div>
            <p className="text-lg font-semibold tracking-tight">NexDownload</p>
            <p className="text-xs text-muted">Independent download management</p>
          </div>
        </div>

        <div className="card p-6">
          <div className="flex items-start gap-3">
            <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-raised text-accent">
              <ShieldCheck className="h-4.5 w-4.5" />
            </div>
            <div>
              <h1 className="text-base font-semibold">Connect to your local engine</h1>
              <p className="mt-1 text-xs leading-relaxed text-muted">
                Every protected API call requires the bearer token generated by the NexDownload
                service. The token never leaves this machine unless you configure a remote
                server yourself.
              </p>
            </div>
          </div>

          <form className="mt-5 space-y-4" onSubmit={submit}>
            <div>
              <label className="label" htmlFor="api-base">
                API address
              </label>
              <div className="relative">
                <Wifi className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-subtle" />
                <Input
                  id="api-base"
                  className="pl-9"
                  value={base}
                  onChange={(event) => setBase(event.target.value)}
                  spellCheck={false}
                  autoComplete="off"
                  placeholder="http://127.0.0.1:47821"
                />
              </div>
            </div>
            <div>
              <label className="label" htmlFor="api-token">
                API token
              </label>
              <div className="relative">
                <KeyRound className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-subtle" />
                <Input
                  id="api-token"
                  className="pl-9 font-mono text-xs"
                  value={tokenValue}
                  onChange={(event) => setTokenValue(event.target.value)}
                  spellCheck={false}
                  autoComplete="off"
                  placeholder="Paste the 64-character token"
                />
              </div>
            </div>

            {error ? (
              <p className="rounded-lg border border-danger/25 bg-danger/10 px-3 py-2 text-xs text-danger">
                {error}
              </p>
            ) : null}

            <Button type="submit" variant="primary" className="w-full" disabled={busy}>
              {busy ? <Loader2 className="h-4 w-4 animate-spin" /> : <KeyRound className="h-4 w-4" />}
              Connect
            </Button>
          </form>

          <div className="mt-5 space-y-2 border-t border-border pt-4 text-[11px] leading-relaxed text-muted">
            {isTauri ? (
              <p>
                The desktop build normally supplies this token automatically. If the service is
                running, restart the application.
              </p>
            ) : (
              <p>
                Running the web client separately? Start <code className="font-mono">nexdownloadd</code>{" "}
                and read the token from <code className="font-mono">api-token</code> in the
                configured data directory.
              </p>
            )}
            <p>
              Use <code className="font-mono">http://127.0.0.1:47821</code> for the default local
              server. LAN access requires TLS and the server&apos;s explicit trust-proxy setting.
            </p>
          </div>
        </div>
      </div>
    </div>
  );
}
